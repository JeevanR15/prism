export function makeT(lang) {
  return (key, vars) => {
    let s = STR[lang]?.[key] ?? STR.en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
    return s
  }
}

// Pick the current language from a {en, te, hi} object, falling back to English.
export function pick(obj, lang) {
  if (obj == null) return ''
  if (typeof obj === 'string' || Array.isArray(obj)) return obj
  return obj[lang] ?? obj.en
}

export function langName(code, uiLang) {
  const l = LANGS.find((x) => x.code === code)
  if (!l) return code
  return uiLang === 'en' ? l.label : l.native
}
